const byRecipeId = new Map(supplements.map((item) => [item.sourceRecipeId, item]));

function normalizeIngredient(value: string): string {
  return value.normalize("NFC").toLocaleLowerCase("vi").replace(/\s+/g, " ").trim();
}

function classifyAddedIngredientRole(value: string): "seasoning" | "aromatic_or_garnish" | "cooking_liquid" | "core_or_variant" {
  const normalized = value.toLocaleLowerCase("vi").normalize("NFD").replace(/[\u0300-\u036f]/g, "").replace(/đ/g, "d");
  if (/(?:muoi|duong|hat nem|bot ngot|mi chinh|tieu|nuoc mam|nuoc tuong|dau hao|sa te|tuong ot|dau me|dau dieu|dau thuc vat|dau an|mat ong|giam|nuoc mau)/.test(normalized)) return "seasoning";
  if (/^nuoc (?:loc|dung|cot dua|dua)/.test(normalized)) return "cooking_liquid";
  if (/^(?:hanh|toi|gung|sa|que|hoa hoi|thao qua|rau mui|ngo ri|rau ram|rau thom|la chanh|thi la|ot|chanh|tac|la dua)/.test(normalized)) return "aromatic_or_garnish";
  return "core_or_variant";
}

export function getSourceInstructionSupplement(sourceRecipeId: string): SourceInstructionSupplement | undefined {
  return byRecipeId.get(sourceRecipeId);
}

export function applySourceInstructionSupplement(detail: SourceRecipeDetail): SourceRecipeDetail {
  const supplement = byRecipeId.get(detail.id);
  if (!supplement || detail.instructions_raw?.trim() || !detail.ingredients?.length) return detail;
  const available = new Set(detail.ingredients.map((item) => normalizeIngredient(item.name)));
  if (!supplement.expectedIngredients.every((name) => available.has(normalizeIngredient(name)))) return detail;
  const optionalAdded = new Set((supplement.optionalAddedIngredients ?? []).map(normalizeIngredient));
  const unmentionedAdded = new Set((supplement.addedIngredientsNotMentionedInSteps ?? []).map(normalizeIngredient));
  const addedIngredients = (supplement.addedIngredients ?? []).map((name) => ({
    name,
    quantity_raw: null,
    quantity_value: null,
    quantity_unit: null,
    usage_status: optionalAdded.has(normalizeIngredient(name)) ? "optional" as const : unmentionedAdded.has(normalizeIngredient(name)) ? "not_mentioned" as const : "mentioned" as const,
    role: classifyAddedIngredientRole(name),
  }));
  return {
    ...detail,
    source_ingredients: detail.ingredients,
    instruction_added_ingredients: addedIngredients,
    ingredients: addedIngredients.length
      ? [...detail.ingredients, ...addedIngredients.map((ingredient) => ({ ...ingredient, instruction_added: true, instruction_usage_status: ingredient.usage_status }))]
      : detail.ingredients,
    instructions_raw: supplement.steps.join("\n\n"),
    instruction_authorship: "independently_authored",
    instruction_review_status: supplement.status,
    instruction_reference_url: supplement.referenceUrl,
    instruction_reference_title: supplement.referenceTitle,
  };
}

